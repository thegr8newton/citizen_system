import heapq

# Normal Queue
normal_queue = []

def enqueue_normal(request):
    normal_queue.append(request)
    print(f"Normal added: {request}")

def dequeue_normal():
    if normal_queue:
        print(f"Normal processed: {normal_queue.pop(0)}")
    else:
        print("Normal queue empty")

# Priority Queue
priority_queue = []

def enqueue_urgent(request, priority):
    heapq.heappush(priority_queue, (priority, request))
    print(f"Urgent added: {request}, priority {priority}")

def dequeue_urgent():
    if priority_queue:
        priority, request = heapq.heappop(priority_queue)
        print(f"Urgent processed: {request}, priority {priority}")
    else:
        print("Urgent queue empty")

