#Q3 UNDO / REDO USING STACKS
undo_stack = []
redo_stack = []
state = []

def do(op):
    state.append(op)
    undo_stack.append(op)
    redo_stack.clear()
    print(f"Performed: {op}, State: {state}")

def undo():
    if undo_stack:
        last = undo_stack.pop()
        state.remove(last)
        redo_stack.append(last)
        print(f"Undo: {last}, State: {state}")

def redo():
    if redo_stack:
        last = redo_stack.pop()
        state.append(last)
        undo_stack.append(last)
        print(f"Redo: {last}, State: {state}")

# DEMO
do("Add Delivery 1")
do("Add Delivery 2")
undo()
redo()

