def dijkstra(start):
    dist={n:float('inf') for n in graph}; dist[start]=0
    h=[(0,start)]
    while h:
        d,n=heapq.heappop(h)
        for nei,w in graph[n]:
            if d+w<dist[nei]:
                dist[nei]=d+w; heapq.heappush(h,(dist[nei],nei))
