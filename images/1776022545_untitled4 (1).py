# Q9 SIMPLE RIDER BST

class Rider:
    def __init__(self,id,name):
        self.id=id; self.name=name
        self.left=None; self.right=None

def insert(root,id,name):
    if not root: return Rider(id,name)
    if id<root.id: root.left=insert(root.left,id,name)
    else: root.right=insert(root.right,id,name)
    return root

def search(root,id):
    if not root or root.id==id: return root
    return search(root.left,id) if id<root.id else search(root.right,id)

def nearest(root,target,closest=None):
    if not root: return closest
    if not closest or abs(root.id-target)<abs(closest.id-target): closest=root
    if target<root.id: return nearest(root.left,target,closest)
    else: return nearest(root.right,target,closest)

